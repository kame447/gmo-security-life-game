/**
 * 濁点・半濁点の点（x, y）。本体は太字で描くので、これらは細いまま右上に離して置き、
 * 本体の線とつながらないようにする（y が負の点は文字の枠より上に出る）。
 */
const DAKUTEN: readonly (readonly [number, number])[] = [[8, -1], [8, 0], [10, -1], [10, 0]];
const HANDAKUTEN: readonly (readonly [number, number])[] = [[9, -2], [8, -1], [10, -1], [9, 0]];
const MARKED: Record<string, [string, typeof DAKUTEN]> = {
  'だ': ['た', DAKUTEN], 'が': ['か', DAKUTEN], 'ビ': ['ヒ', DAKUTEN], 'パ': ['ハ', HANDAKUTEN],
};
/** Bold doubles each body dot to the right, so a character is one dot wider than its cell. */
const ADVANCE = GLYPH_W + 1 + GAP;
/** Darken the sign colour for the text so thin kana stand out on the pale board. */
const INK = -0.35;

export interface GlyphDots { body: [number, number][]; marks: [number, number][] }

/** The dots of one character, or undefined when the sign font does not have it. */
export function glyphDots(ch: string): GlyphDots | undefined {
  const marked = MARKED[ch];
  const base = BASE[marked ? marked[0] : ch];
  if (!base) return undefined;
  const body: [number, number][] = [];
  base.forEach((row, y) => { for (let x = 0; x < row.length; x++) if (row[x] === '#') body.push([x, y]); });
  return { body, marks: marked ? marked[1].map(([x, y]) => [x, y] as [number, number]) : [] };
}

export function hasGlyphs(text: string): boolean {
  return [...text].every(ch => glyphDots(ch) !== undefined);
}

export function signTextWidth(text: string): number {
  const n = [...text].length;
  return n ? (n - 1) * ADVANCE + GLYPH_W + 1 : 0;
}

function darken(hex: string, factor: number): string {
  const n = Number.parseInt(hex.slice(1), 16);
  const [r, g, b] = [(n >> 16) & 255, (n >> 8) & 255, n & 255].map(v => Math.round(v * (1 + factor)));
  return `#${((1 << 24) | (r << 16) | (g << 8) | b).toString(16).slice(1)}`;
}

/**
 * Draw bold text centred on `center`, with the top of the 10-dot cell at `y` (marks rise up to 2 dots above it).
 * The colour is the sign's colour; the text is drawn darker than it.
 */
export function drawSignText(c: C2D, text: string, center: number, y: number, color: string): void {
  const ink = darken(color, INK);
  let x = Math.round(center - signTextWidth(text) / 2);
  for (const ch of text) {
    const dots = glyphDots(ch);
    if (dots) {
      for (const [dx, dy] of dots.body) R(c, ink, x + dx, y + dy, 2, 1);
      for (const [dx, dy] of dots.marks) R(c, ink, x + dx, y + dy, 1, 1);
    }
    x += ADVANCE;
  }
}
